    // Icône d'erreur sous forme d'entité GeoJSON pour le calque SDK « Color Errors icons »
    // (remplace l'ancien calque OpenLayers posé sur W.map).
    function iconFeature(icon, geometry, pos, objId) {
        const entry = ceErrorDB.find(item => item.id === icon);
        if (!entry || !geometry || !geometry.coordinates) return null;
        const svg = "data:image/svg+xml;base64," + btoa(
            `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="640" viewBox="0 0 640 640">
                ${ls.iBackground ? "<rect x='0' y='0' width='640' height='640'  rx='100' ry='100' fill='#fff' fill-opacity='1'/>" : ""}
                <path d="${entry.icon}" fill="${entry.level}"/>
            </svg>`
        );
        const c = geometry.coordinates;
        let pt = null;
        if (geometry.type === "LineString" && c.length >= 2) {
            if (c.length === 2) {
                pt = [(((c[0][0] + c[1][0]) / 2) + c[0][0]) / 2, (((c[0][1] + c[1][1]) / 2) + c[0][1]) / 2];
            } else {
                for (let i = 0; i < c.length - 1; i++) {
                    if (i % 3 === 1) pt = [(c[i][0] * 0.75) + (c[i + 1][0] * 0.25), (c[i][1] * 0.75) + (c[i + 1][1] * 0.25)];
                }
            }
            if (!pt) pt = c[0];
        } else if (geometry.type === "Point") pt = c;
        else if (geometry.type === "Polygon") pt = c[0] && c[0][0];
        else if (geometry.type === "MultiPolygon") pt = c[0] && c[0][0] && c[0][0][0];
        if (!pt) return null;
        const errSize = Number($id('iconErrSize')?.value || ls.iconSize || 25);
        return {
            type: "Feature",
            id: `ce-icon-${icon}-${objId}-${pos}`,
            geometry: { type: "Point", coordinates: [pt[0], pt[1]] },
            properties: {
                icon: svg,
                size: errSize,
                opacity: Number($id('iconErrOpacity')?.value ?? ls.iconOpacity ?? 1),
                yOffset: -Number($id("vpErrSize")?.value || ls.vpSize || 12) - 5 - (pos * 1.1) * errSize,
            },
        };
    }


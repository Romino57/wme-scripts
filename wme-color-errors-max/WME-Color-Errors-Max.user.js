    async function onRaiseLocks() {
        if (!(wmeUserRank > 4)) { setLockStatus("Réservé aux éditeurs de niveau 5 et plus.", "#c60"); return; }
        const sel = await wmeSDK.Editing.getSelection();
        if (!sel || !sel.ids || !sel.ids.length || !["segment", "venue"].includes(sel.objectType)) {
            setLockStatus("Sélectionne d'abord des segments ou des lieux dans WME.", "#c60"); return;
        }
        if (sel.ids.length > RAISE_MAX) { setLockStatus(`${sel.ids.length} objets sélectionnés : le maximum est ${RAISE_MAX} par clic.`, "#c60"); return; }

        const plan = [], skipped = { ok: 0, higher: 0, type: 0, ignored: 0, perm: 0, staff: 0 };
        for (const id of sel.ids) {
            let obj, exp, errId, perm;
            if (sel.objectType === "segment") {
                obj = await wmeSDK.DataModel.Segments.getById({ segmentId: id });
                if (!obj) continue;
                exp = expectedSegmentLock(obj); errId = "_seg_LockValue";
                try { perm = await wmeSDK.DataModel.Segments.hasPermissions({ segmentId: id }); } catch (e) { perm = false; }
            } else {
                obj = await wmeSDK.DataModel.Venues.getById({ venueId: String(id) });
                if (!obj) continue;
                const cat = (obj.categories || []).find(c => VENUE_TYPE_LOCK[c] !== undefined);
                exp = cat ? { target: VENUE_TYPE_LOCK[cat], key: `auto_lock_${cat}`, why: cat } : null; errId = "_poi_LockValue";
                try { perm = await wmeSDK.DataModel.Venues.hasPermissions({ venueId: String(id) }); } catch (e) { perm = false; }
            }
            const cur = Number(obj.lockRank) || 0;
            if (cur > 4) { skipped.staff++; continue; }               // L6 et staff : jamais touché
            if (!exp || ls[exp.key] !== true) { skipped.type++; continue; } // type non coché (ou hors table)
            if (isIgnored(id, errId)) { skipped.ignored++; continue; }
            if (!perm) { skipped.perm++; continue; }
            if (exp.target === cur) { skipped.ok++; continue; }
            if (exp.target < cur) { skipped.higher++; continue; }     // jamais abaisser
            plan.push({ id, kind: sel.objectType, from: cur, to: exp.target, why: exp.why });
        }

        const notes = [];
        if (skipped.ok) notes.push(`${skipped.ok} déjà au bon niveau`);
        if (skipped.higher) notes.push(`${skipped.higher} déjà plus haut (jamais abaissé)`);
        if (skipped.type) notes.push(`${skipped.type} de type non coché`);
        if (skipped.ignored) notes.push(`${skipped.ignored} ignoré(s)`);
        if (skipped.perm) notes.push(`${skipped.perm} non modifiable(s)`);
        if (skipped.staff) notes.push(`${skipped.staff} en L6/staff`);
        if (!plan.length) { setLockStatus(`Rien à relever.${notes.length ? "\n" + notes.join(", ") + "." : ""}`, "#555"); return; }

        const lines = plan.slice(0, 10).map(p => `• ${p.kind === "segment" ? "Segment" : "Lieu"} ${p.id} (${p.why}) : niveau ${p.from + 1} → ${p.to + 1}`);
        const ok = window.confirm(`Relever ${plan.length} verrou(s) ?\n\n${lines.join("\n")}${plan.length > 10 ? `\n… et ${plan.length - 10} autre(s)` : ""}`
            + `${notes.length ? `\n\nNon modifiés : ${notes.join(", ")}.` : ""}\n\nAucun verrou n'est abaissé. Rien n'est enregistré : vérifie puis clique sur « Enregistrer ».`);
        if (!ok) return;

        let done = 0, failed = 0;
        for (const p of plan) {
            try {
                if (p.kind === "segment") await wmeSDK.DataModel.Segments.updateSegment({ segmentId: p.id, lockRank: p.to });
                else await wmeSDK.DataModel.Venues.updateVenue({ venueId: String(p.id), lockRank: p.to });
                done++;
            } catch (e) { failed++; console.warn("[WME Color Errors] Verrou refusé", p, e); }
        }
        setLockStatus(`${done} verrou(s) relevé(s)${failed ? `, ${failed} refusé(s) par WME` : ""}. Vérifie puis clique sur « Enregistrer ».`, failed ? "#c00" : "#080");
        scheduleErrors();
    }

    function formatTelGoogle(phone) {
        const lpn = libphonenumber,
            pnu = lpn.PhoneNumberUtil.getInstance(),
            pnf = lpn.PhoneNumberFormat,
            pnt = lpn.PhoneNumberType;

        WMECE_log(`Formatage du numéro : ${phone}`);

        // Numéro à 4 chiffres (ex: numéros courts locaux)
        const stripped = phone.replaceAll(/\s+/g, '').replaceAll(/\D/g, '');
        if (stripped.length === 4) return { formatted: `${stripped.slice(0, 2)} ${stripped.slice(2)}`, valid: true };

        try {
            const aPhone = pnu.parseAndKeepRawInput(phone, phone.startsWith("+") ? null : "FR");
            const region = pnu.getRegionCodeForNumber(aPhone);
            const type = pnu.getNumberType(aPhone);
            const typeLabel = Object.keys(pnt).find(key => pnt[key] === type);

            WMECE_log(`Analyse : ${phone} | pays: ${region}, type: ${typeLabel}`);

            if (!pnu.isValidNumber(aPhone)) {
                console.warn(`[WME Color Errors] Numéro non reconnu, ignoré : "${phone}"`);
                return { formatted: phone, valid: false, unknown: true };
            }

            const formatted = ([3, 4, 5, 9].includes(type) && region === "FR")
                ? pnu.format(aPhone, pnf.NATIONAL)
                : pnu.format(aPhone, pnf.INTERNATIONAL);

            return { formatted, valid: true };

        } catch (e) {
            console.warn(`[WME Color Errors] Impossible de parser "${phone}" :`, e.message);
            return { formatted: phone, valid: false, unknown: true };
        }
    }


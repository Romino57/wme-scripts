    const LS_IGNORED = 'WMEColorErrors_ignored';
    let ignoredCache = null; // cache mémoire, invalidé à chaque écriture — évite de
                              // re-parser le localStorage à chaque appel de isIgnored()

    function ignoredLoad() {
        if (ignoredCache !== null) return ignoredCache;
        try { ignoredCache = JSON.parse(localStorage.getItem(LS_IGNORED) || '{}'); }
        catch (e) { ignoredCache = {}; }
        return ignoredCache;
    }

    function ignoredSave(data) {
        ignoredCache = data;
        localStorage.setItem(LS_IGNORED, JSON.stringify(data));
    }

    function ignoredKey(id, err) {
        return `${id}_${err}`;
    }

    function ignoredAdd(id, err, geo) {
        const data = ignoredLoad();
        data[ignoredKey(id, err)] = { date: Date.now(), geo: geo || null, wmeId: id };
        ignoredSave(data);
    }

    function ignoredLocate(entry) {
        if (!entry || !entry.geo) { WMECE_log("Localisation impossible : géométrie manquante"); return; }
        const geo = entry.geo;
        let lon, lat;

        if (geo.type === "Point") {
            [lon, lat] = geo.coordinates;
        } else if (geo.type === "LineString") {
            const mid = Math.floor(geo.coordinates.length / 2);
            [lon, lat] = geo.coordinates[mid];
        } else if (geo.type === "Polygon") {
            // centroïde approximatif du premier anneau
            const ring = geo.coordinates[0];
            lon = ring.reduce((s, c) => s + c[0], 0) / ring.length;
            lat = ring.reduce((s, c) => s + c[1], 0) / ring.length;
        } else return;

        try { wmeSDK.Map.setMapCenter({ lonLat: { lon, lat }, zoomLevel: 17 }); } catch (e) { WMECE_log(e); }

        // Sélection de l'objet si l'ID est numérique (segment/node) ou string (venue)
        if (entry.wmeId) {
            try {
                const id = entry.wmeId;
                if (typeof id === "string" && isNaN(Number(id))) {
                    // Venue (GUID)
                    wmeSDK.Editing.setSelection({ selection: { objectType: "venue", ids: [id] } });
                } else {
                    // Segment ou nœud : on tente segment d'abord
                    const numId = Number(id);
                    const errId = Object.keys(ignoredLoad()).find(k => k.startsWith(id + '_'));
                    if (errId && errId.includes('_nod_')) {
                        wmeSDK.Editing.setSelection({ selection: { objectType: "node", ids: [numId] } });
                    } else {
                        wmeSDK.Editing.setSelection({ selection: { objectType: "segment", ids: [numId] } });
                    }
                }
            } catch (e) { WMECE_log("Sélection impossible : " + e.message); }
        }
    }

    function ignoredRemove(key) {
        const data = ignoredLoad();
        delete data[key];
        ignoredSave(data);
    }

    function ignoredClear() {
        ignoredCache = {};
        localStorage.removeItem(LS_IGNORED);
    }

    function ignoredPurgeExpired() {
        const ttlDays = ls && ls.ignoredTTL !== undefined ? ls.ignoredTTL : 30;
        if (ttlDays === 0) return; // 0 = permanent
        const data = ignoredLoad();
        const cutoff = Date.now() - ttlDays * 86400000;
        let changed = false;
        for (const k of Object.keys(data)) {
            if (data[k].date < cutoff) { delete data[k]; changed = true; }
        }
        if (changed) ignoredSave(data);
    }

    function isIgnored(id, err) {
        const data = ignoredLoad();
        const entry = data[ignoredKey(id, err)];
        if (!entry) return false;
        const ttlDays = ls && ls.ignoredTTL !== undefined ? ls.ignoredTTL : 30;
        if (ttlDays === 0) return true; // permanent
        return (Date.now() - entry.date) < ttlDays * 86400000;
    }

    function lsSize() {
        const keys = ['WMEColorErrors', LS_IGNORED];
        let total = 0;
        keys.forEach(k => { total += (localStorage.getItem(k) || '').length * 2; }); // UTF-16 : ~2 octets/char
        return total;
    }

    function lsSizeStr() {
        const b = lsSize();
        if (b < 1024) return b + ' o';
        if (b < 1048576) return (b / 1024).toFixed(1) + ' Ko';
        return (b / 1048576).toFixed(2) + ' Mo';
    }


    const SEG_TYPE_LOCK = { 1: 0, 2: 2, 3: 4, 4: 4, 5: 0, 6: 4, 7: 3, 8: 0, 9: 0, 10: 0, 15: 0, 16: 0, 17: 0, 18: 4, 19: 0, 20: 0, 22: 0 };

    // Péage : lu sur l'objet SDK s'il est exposé, sinon (repli tant qu'il existe) sur l'objet interne de WME.
    function segHasToll(seg) {
        for (const k of ["fwdToll", "revToll", "hasToll", "isToll"]) if (seg && seg[k] === true) return true;
        try {
            const legacyAttrs = window.W?.model?.segments?.getObjectById?.(seg.id)?.attributes;
            return !!(legacyAttrs && (legacyAttrs.fwdToll || legacyAttrs.revToll));
        } catch (e) { return false; }
    }

    // Feux tricolores (dangers permanents) rattachés à l'un des segments : SDK d'abord, puis repli.
    async function segmentsHaveTrafficLight(segmentIds) {
        try {
            const ph = wmeSDK.DataModel.PermanentHazards;
            if (ph && typeof ph.getAll === "function") {
                const all = (await ph.getAll()) || [];
                return all.some(h => (h.type === "TRAFFIC_LIGHT" || h.type === 12) && segmentIds.includes(h.segmentId));
            }
        } catch (e) { WMECE_log(e); }
        try {
            const objs = Object.values(window.W?.model?.permanentHazards?.objects || {});
            return objs.some(h => h.attributes?.type === 12 && segmentIds.includes(h.attributes?.segmentId));
        } catch (e) { return false; }
    }

